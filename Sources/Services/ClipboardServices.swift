/// Polls the general pasteboard twice a second and feeds new text into the store,
/// skipping concealed content, ignored apps, oversized items and the app's own copies.
@MainActor
final class PasteboardMonitor {
    static let shared = PasteboardMonitor()
    static let internalType = NSPasteboard.PasteboardType("com.turhe123.reuserankclips.internal")
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]
    private static let maxBytes = 1_000_000

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        let types = pb.types ?? []
        if types.contains(Self.internalType) { return }
        if types.contains(where: { Self.skippedTypes.contains($0.rawValue) }) { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, Prefs.ignoredApps.contains(source) { return }
        guard let text = pb.string(forType: .string),
              text.utf8.count <= Self.maxBytes,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        ClipStore.shared.capture(text, sourceApp: source)
    }
}

/// Puts a clip on the pasteboard and, when allowed, refocuses the previous app and sends ⌘V.
@MainActor
final class Paster {
    static let shared = Paster()
    private(set) var previousApp: NSRunningApplication?

    init() {
        if let front = NSWorkspace.shared.frontmostApplication, front != .current { previousApp = front }
        NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] note in
            guard let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication,
                  app != .current else { return }
            MainActor.assumeIsolated { self?.previousApp = app }
        }
    }

    static var isTrusted: Bool { AXIsProcessTrusted() }

    static func requestAccessibility() {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }

    static func openAccessibilitySettings() {
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
            NSWorkspace.shared.open(url)
        }
    }

    /// Copies (tagged as internal so it counts as a use, not a capture) and optionally pastes.
    func paste(_ clip: Clip, closing window: NSWindow?) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.declareTypes([.string, PasteboardMonitor.internalType], owner: nil)
        pb.setString(clip.text, forType: .string)
        pb.setData(Data(), forType: PasteboardMonitor.internalType)
        ClipStore.shared.recordUse(clip.id)
        window?.close()

        guard Prefs.pasteImmediately, Self.isTrusted else { return }
        let target = previousApp
        NSApp.hide(nil)
        target?.activate()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.25) {
            Self.sendCommandV()
        }
    }

    private static func sendCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}

/// Registers one system-wide hotkey via the Carbon hotkey API (no Accessibility needed).
@MainActor
final class HotKeyManager {
    static let shared = HotKeyManager()
    var onPress: (() -> Void)?
    private var hotKeyRef: EventHotKeyRef?
    private var handlerRef: EventHandlerRef?

    func registerFromDefaults() {
        let defaults = UserDefaults.standard
        register(keyCode: UInt32(defaults.integer(forKey: Prefs.Key.hotkeyCode)),
                 modifiers: UInt32(defaults.integer(forKey: Prefs.Key.hotkeyMods)))
    }

    func register(keyCode: UInt32, modifiers: UInt32) {
        unregister()
        if handlerRef == nil {
            var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
            InstallEventHandler(GetApplicationEventTarget(), { _, _, _ in
                Task { @MainActor in HotKeyManager.shared.onPress?() }
                return noErr
            }, 1, &spec, nil, &handlerRef)
        }
        guard modifiers != 0 else { return }
        let id = EventHotKeyID(signature: OSType(0x5252_4331), id: 1)
        RegisterEventHotKey(keyCode, modifiers, id, GetApplicationEventTarget(), 0, &hotKeyRef)
    }

    func unregister() {
        if let hotKeyRef { UnregisterEventHotKey(hotKeyRef) }
        hotKeyRef = nil
    }

    /// Converts AppKit modifier flags to Carbon modifier bits plus a display string.
    static func carbonModifiers(_ flags: NSEvent.ModifierFlags) -> (UInt32, String) {
        var bits: UInt32 = 0
        var name = ""
        if flags.contains(.control) { bits |= UInt32(controlKey); name += "⌃" }
        if flags.contains(.option) { bits |= UInt32(optionKey); name += "⌥" }
        if flags.contains(.shift) { bits |= UInt32(shiftKey); name += "⇧" }
        if flags.contains(.command) { bits |= UInt32(cmdKey); name += "⌘" }
        return (bits, name)
    }
}
